/**
 * One-shot split of content/docs into tutor/ and student/.
 * Safe to run only while articles still live in the section folders at content/docs/*.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsRoot = path.join(appRoot, 'content/docs');

const studentExclude = new Set([
  'classrooms/invite-tutor-flow.mdx',
  'classrooms/create-group.mdx',
  'classrooms/group-classroom-manage.mdx',
  'classrooms/student-material-access.mdx',
  'lessons-and-schedule/create-move-lesson.mdx',
  'payments/create-invoice.mdx',
  'payments/control-payments.mdx',
  'board-and-notes/board-during-call.mdx',
]);

const tutorExclude = new Set(['classrooms/accept-invite.mdx']);

const sectionOrder = [
  'getting-started',
  'classrooms',
  'lessons-and-schedule',
  'board-and-notes',
  'video-lesson',
  'payments',
  'profile-settings',
  'install-and-help',
  'troubleshooting',
];

function walk(dir, base = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'tutor' || entry.name === 'student') continue;
    const rel = base ? `${base}/${entry.name}` : entry.name;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, rel));
    else if (entry.name.endsWith('.mdx') || entry.name === 'meta.json') out.push(rel);
  }
  return out;
}

function slugFromMdx(rel) {
  return rel
    .replace(/\.mdx$/, '')
    .replace(/\/index$/, '')
    .replace(/^index$/, '');
}

function prefixLinks(text, role) {
  return text.replace(/\]\((\/(?!\/)[^)\s]+)\)/g, (match, url) => {
    if (
      url.startsWith('/tutor/') ||
      url.startsWith('/student/') ||
      url === '/tutor' ||
      url === '/student'
    ) {
      return match;
    }
    return `](/${role}${url})`;
  });
}

function pageExists(dir, page) {
  return (
    fs.existsSync(path.join(dir, `${page}.mdx`)) ||
    fs.existsSync(path.join(dir, page, 'index.mdx')) ||
    fs.existsSync(path.join(dir, page, 'meta.json'))
  );
}

if (fs.existsSync(path.join(docsRoot, 'tutor', 'meta.json'))) {
  console.error('tutor/ already exists, skip split');
  process.exit(1);
}

const files = walk(docsRoot).filter((rel) => !rel.startsWith('index.mdx'));
const redirects = [];

for (const role of ['tutor', 'student']) {
  const exclude = role === 'student' ? studentExclude : tutorExclude;
  for (const rel of files) {
    if (rel.endsWith('.mdx') && exclude.has(rel)) continue;
    const from = path.join(docsRoot, rel);
    const to = path.join(docsRoot, role, rel);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    let text = fs.readFileSync(from, 'utf8');
    if (rel.endsWith('.mdx')) text = prefixLinks(text, role);
    fs.writeFileSync(to, text);
  }

  for (const section of sectionOrder) {
    const metaPath = path.join(docsRoot, role, section, 'meta.json');
    if (!fs.existsSync(metaPath)) continue;
    const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
    meta.pages = meta.pages.filter((page) => pageExists(path.join(docsRoot, role, section), page));
    fs.writeFileSync(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
  }

  const roleMeta = {
    title: role === 'tutor' ? 'Репетитор' : 'Ученик',
    pages: [
      'index',
      ...sectionOrder.filter((section) =>
        fs.existsSync(path.join(docsRoot, role, section, 'meta.json')),
      ),
    ],
  };
  fs.writeFileSync(
    path.join(docsRoot, role, 'meta.json'),
    `${JSON.stringify(roleMeta, null, 2)}\n`,
  );
}

const originalMdx = files.filter((rel) => rel.endsWith('.mdx'));
for (const rel of originalMdx) {
  const slug = slugFromMdx(rel);
  const destination =
    rel === 'classrooms/accept-invite.mdx' ? `/student/${slug}` : `/tutor/${slug}`;
  redirects.push({ source: `/${slug}`, destination });
  fs.rmSync(path.join(docsRoot, rel));
}

for (const section of sectionOrder) {
  fs.rmSync(path.join(docsRoot, section), { recursive: true, force: true });
}

fs.writeFileSync(
  path.join(docsRoot, 'meta.json'),
  `${JSON.stringify({ title: 'База знаний', pages: ['index', 'tutor', 'student'] }, null, 2)}\n`,
);
fs.writeFileSync(
  path.join(appRoot, 'legacy-redirects.json'),
  `${JSON.stringify(redirects, null, 2)}\n`,
);

const slugs = (role) =>
  walk(path.join(docsRoot, role))
    .filter((rel) => rel.endsWith('.mdx'))
    .map(slugFromMdx)
    .filter(Boolean)
    .sort();

const slugModule = `/* Generated by scripts/split-docs-roles.mjs */\nexport const tutorSlugs = ${JSON.stringify(slugs('tutor'), null, 2)} as const;\n\nexport const studentSlugs = ${JSON.stringify(slugs('student'), null, 2)} as const;\n\nexport const roleAliases: Record<string, Partial<Record<'tutor' | 'student', string>>> = {\n  'classrooms/invite-tutor-flow': { student: 'classrooms/accept-invite' },\n  'classrooms/accept-invite': { tutor: 'classrooms/invite-tutor-flow' },\n};\n`;
fs.writeFileSync(path.join(appRoot, 'lib/doc-slugs.ts'), slugModule);
console.log(
  `redirects ${redirects.length}, tutor ${slugs('tutor').length}, student ${slugs('student').length}`,
);
